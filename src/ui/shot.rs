//! Screenshot UI (GNOME-style overlay: Selection / Screen + shutter), screen recording, shortcuts.
use super::*;
use crate::config::{accel_name, expand_home, parse_accel};
use std::process::Child;

pub struct ShotUi {
    pub pane: Pane,
    pub img: Canvas,
    pub mode: u8, // 0 selection, 1 screen
    pub sel: Option<R>,
    pub drag: Option<(f32, f32)>,
}

pub struct Recorder {
    pub child: Child,
    pub path: std::path::PathBuf,
    pub started: Instant,
    pub stopping: Option<Instant>,
}

fn stamp() -> String {
    let t = crate::sys::local_time(crate::sys::now_epoch());
    format!("{:04}-{:02}-{:02} {:02}-{:02}-{:02}", t.year + 1900, t.mon + 1, t.mday, t.hour, t.min, t.sec)
}

impl Shell {
    // ---------------- shortcuts ----------------
    pub fn register_shortcuts(&mut self) {
        self.p.ungrab_shortcuts();
        let list: Vec<(u32, String)> = self.cfg.sc.iter().enumerate().map(|(i, a)| (i as u32 + 1, a.clone())).collect();
        let mut ok = 0;
        for (id, accel) in list {
            if let Some((sym, mods)) = parse_accel(&accel) {
                if self.p.grab_shortcut(id, sym, mods) {
                    ok += 1;
                }
            }
        }
        self.shortcuts_ok = ok;
    }

    // ---------------- capture helpers ----------------
    fn hide_shell_for_capture(&mut self, hide: bool) {
        for id in [self.bar.as_ref().map(|b| b.id), self.dock.as_ref().map(|d| d.id), self.banner.as_ref().map(|b| b.pane.id), self.pop.as_ref().map(|p| p.pane.id), self.catcher].into_iter().flatten() {
            self.p.set_visible(id, !hide);
        }
        self.p.flush();
    }

    fn grab_screen(&mut self) -> Option<Canvas> {
        self.close_popup();
        self.close_grid();
        self.close_settings();
        self.hide_shell_for_capture(true);
        std::thread::sleep(Duration::from_millis(220));
        let _ = self.p.dispatch();
        let o = self.out();
        let img = self.p.capture(o.x, o.y, o.w, o.h);
        self.hide_shell_for_capture(false);
        self.apply_visibility();
        self.mark_all();
        img
    }

    pub fn open_screenshot(&mut self, mode: u8) {
        if self.shot.is_some() {
            return;
        }
        let img = match self.grab_screen() {
            Some(i) => i,
            None => {
                self.toast("Screenshots are not supported by this session");
                return;
            }
        };
        let o = self.out();
        let mut sp = SurfSpec::new(Kind::Overlay);
        sp.w = o.w;
        sp.h = o.h;
        sp.keyboard = true;
        let id = self.p.create(&sp);
        self.p.set_visible(id, true);
        self.shot = Some(ShotUi { pane: Pane::new(id, o.w, o.h), img, mode, sel: None, drag: None });
    }

    pub fn close_screenshot(&mut self) {
        if let Some(s) = self.shot.take() {
            self.p.destroy(s.pane.id);
            self.restore_focus();
        }
    }

    pub fn shot_instant(&mut self) {
        if let Some(img) = self.grab_screen() {
            self.save_screenshot(&img, None);
        } else {
            self.toast("Screenshots are not supported by this session");
        }
    }

    fn save_screenshot(&mut self, img: &Canvas, region: Option<R>) {
        let dir = expand_home(&self.cfg.shot_dir);
        if std::fs::create_dir_all(&dir).is_err() {
            self.toast("Cannot create the screenshot folder");
            return;
        }
        let (rx, ry, rw, rh) = match region {
            Some(r) => (r.0.max(0.0) as usize, r.1.max(0.0) as usize, r.2 as usize, r.3 as usize),
            None => (0, 0, img.w, img.h),
        };
        let png = crate::pngenc::encode(img, rx, ry, rw, rh);
        let path = dir.join(format!("Screenshot from {}.png", stamp()));
        match std::fs::write(&path, &png) {
            Ok(_) => self.local_notify("Screenshot captured", &path.to_string_lossy(), "camera-photo-symbolic", &path.to_string_lossy()),
            Err(e) => self.toast(&format!("Could not save screenshot: {}", e)),
        }
    }

    /// Notification generated by the shell itself (banner + date menu entry).
    pub fn local_notify(&mut self, summary: &str, body: &str, icon: &str, data: &str) {
        if let Some(sv) = &mut self.svc {
            let id = sv.next_id;
            sv.next_id = sv.next_id.wrapping_add(1).max(1);
            sv.notifs.push(crate::svc::Notif {
                id,
                app: "lumen-shell".into(),
                icon: icon.into(),
                summary: summary.into(),
                body: body.into(),
                actions: vec![("default".into(), "Open".into()), ("open-folder".into(), "Show in Folder".into())],
                urgency: 1,
                expire_ms: 6000,
                time: crate::sys::now_epoch(),
                data: data.into(),
                banner_until: Some(Instant::now() + Duration::from_secs(6)),
                ..Default::default()
            });
            self.update_banner();
            if let Some(b) = &mut self.bar {
                b.dirty = true;
            }
        } else {
            self.toast(summary);
        }
    }

    pub fn local_notif_action(&mut self, id: u32, key: &str) -> bool {
        let n = match self.svc.as_ref().and_then(|s| s.notifs.iter().find(|n| n.id == id && n.app == "lumen-shell")) {
            Some(n) => n.clone(),
            None => return false,
        };
        let p = std::path::PathBuf::from(&n.data);
        let target = if key == "open-folder" { p.parent().map(|d| d.to_path_buf()).unwrap_or(p.clone()) } else { p };
        self.spawn_cmd(&["xdg-open", &target.to_string_lossy()]);
        if let Some(s) = &mut self.svc {
            s.notifs.retain(|x| x.id != id);
        }
        self.update_banner();
        true
    }

    // ---------------- overlay input/draw ----------------
    pub fn shot_key(&mut self, sym: u32) {
        match sym {
            0xff1b => self.close_screenshot(),
            0xff0d | 0x20 | 0xff8d => self.shot_capture(),
            _ => {}
        }
    }

    pub fn shot_capture(&mut self) {
        let (region, img) = match &self.shot {
            Some(s) => {
                let r = if s.mode == 0 { s.sel } else { None };
                if s.mode == 0 && r.is_none() {
                    self.toast("Drag to select an area first");
                    return;
                }
                (r, s.img.clone())
            }
            None => return,
        };
        self.close_screenshot();
        self.save_screenshot(&img, region);
    }

    pub fn shot_pointer(&mut self, x: f32, y: f32, what: Ptr) {
        let s = self.s;
        let act = {
            let sh = self.shot.as_mut().unwrap();
            sh.pane.hit_at(x, y).map(|i| sh.pane.hits[i].1.clone())
        };
        match what {
            Ptr::Down(1) => {
                match act {
                    Some(Act::ShotMode(m)) => {
                        if let Some(sh) = &mut self.shot {
                            sh.mode = m;
                            sh.pane.dirty = true;
                        }
                    }
                    Some(Act::ShotCapture) => self.shot_capture(),
                    Some(Act::ShotClose) => self.close_screenshot(),
                    Some(Act::ShotRecord) => {
                        let region = self.shot.as_ref().and_then(|s| if s.mode == 0 { s.sel } else { None });
                        self.close_screenshot();
                        self.start_record(region);
                    }
                    _ => {
                        if let Some(sh) = &mut self.shot {
                            if sh.mode == 0 {
                                sh.drag = Some((x, y));
                                sh.sel = None;
                                sh.pane.dirty = true;
                            }
                        }
                    }
                }
            }
            Ptr::Move => {
                if let Some(sh) = &mut self.shot {
                    if let Some((x0, y0)) = sh.drag {
                        let (a, b) = (x0.min(x), y0.min(y));
                        let (w, h) = ((x - x0).abs(), (y - y0).abs());
                        sh.sel = Some((a.max(0.0), b.max(0.0), w, h));
                        sh.pane.dirty = true;
                    }
                }
            }
            Ptr::Up(1) => {
                if let Some(sh) = &mut self.shot {
                    if sh.drag.take().is_some() {
                        if sh.sel.map_or(false, |r| r.2 < 8.0 * s || r.3 < 8.0 * s) {
                            sh.sel = None;
                        }
                        sh.pane.dirty = true;
                    }
                }
            }
            _ => {}
        }
    }

    pub fn draw_shot(&mut self) {
        let mut sh = match self.shot.take() {
            Some(s) => s,
            None => return,
        };
        sh.pane.dirty = false;
        let s = self.s;
        let th = self.th.clone();
        let (w, h) = (sh.pane.w as f32, sh.pane.h as f32);
        let cv = &mut sh.pane.cv;
        cv.px.copy_from_slice(&sh.img.px);
        let dim = |cv: &mut Canvas, x0: usize, y0: usize, x1: usize, y1: usize| {
            for y in y0..y1.min(cv.h) {
                for x in x0..x1.min(cv.w) {
                    let p = cv.px[y * cv.w + x];
                    let (r, g, b) = (((p >> 16) & 255) * 11 / 20, ((p >> 8) & 255) * 11 / 20, (p & 255) * 11 / 20);
                    cv.px[y * cv.w + x] = 0xFF000000 | (r << 16) | (g << 8) | b;
                }
            }
        };
        match (sh.mode, sh.sel) {
            (0, Some(r)) => {
                let (x0, y0, x1, y1) = (r.0 as usize, r.1 as usize, (r.0 + r.2) as usize, (r.1 + r.3) as usize);
                dim(cv, 0, 0, cv.w, y0);
                dim(cv, 0, y1, cv.w, cv.h);
                dim(cv, 0, y0, x0, y1);
                dim(cv, x1, y0, cv.w, y1);
                cv.stroke_rrect(r.0, r.1, r.2, r.3, 0.0, 2.0 * s, 0xFFFFFFFF);
            }
            (0, None) => dim(cv, 0, 0, cv.w, cv.h),
            _ => {}
        }
        let mut hits: Vec<(R, Act)> = vec![];
        let mut pt = Paint { tx: &mut self.tx, txb: &mut self.txb, icons: &mut self.icons, th: &self.th, s };
        let px = pt.px(1.0);
        if let (0, Some(r)) = (sh.mode, sh.sel) {
            let label = format!("{} × {}", r.2 as i32, r.3 as i32);
            let lw = pt.text_w(&label, px * 0.9, true) + 20.0 * s;
            cv.fill_rrect(r.0, (r.1 - 30.0 * s).max(4.0), lw, 24.0 * s, 12.0 * s, 0xE0000000);
            pt.text(cv, &label, px * 0.9, r.0 + 10.0 * s, (r.1 - 30.0 * s).max(4.0) + 12.0 * s, 0xFFFFFFFF, true);
        } else if sh.mode == 0 {
            pt.text_center(cv, "Drag to select an area", px * 1.2, w / 2.0, h / 2.0, 0xFFFFFFFF, true);
        }
        // toolbar
        let tw = 470.0 * s;
        let th_ = 64.0 * s;
        let (tx0, ty0) = ((w - tw) / 2.0, h - th_ - 40.0 * s);
        cv.fill_rrect(tx0, ty0, tw, th_, th_ / 2.0, with_alpha(0xFF1E1E1E, 0.94));
        cv.stroke_rrect(tx0 + 0.5, ty0 + 0.5, tw - 1.0, th_ - 1.0, th_ / 2.0, 1.0, with_alpha(0xFFFFFFFF, 0.12));
        let mut bx = tx0 + 14.0 * s;
        for (i, (lab, mode)) in [("Selection", 0u8), ("Screen", 1u8)].iter().enumerate() {
            let bw = 108.0 * s;
            let r: R = (bx + i as f32 * (bw + 6.0 * s), ty0 + 10.0 * s, bw, th_ - 20.0 * s);
            let on = sh.mode == *mode;
            cv.fill_rrect(r.0, r.1, r.2, r.3, r.3 / 2.0, if on { th.accent } else { with_alpha(0xFFFFFFFF, 0.08) });
            pt.text_center(cv, lab, px, r.0 + r.2 / 2.0, r.1 + r.3 / 2.0, if on { th.accent_fg } else { 0xFFFFFFFF }, true);
            hits.push((r, Act::ShotMode(*mode)));
        }
        let sr: R = (tx0 + 14.0 * s + 2.0 * 114.0 * s + 18.0 * s, ty0 + 8.0 * s, th_ - 16.0 * s, th_ - 16.0 * s);
        cv.fill_circle(sr.0 + sr.2 / 2.0, sr.1 + sr.3 / 2.0, sr.2 / 2.0, 0xFFFFFFFF);
        cv.fill_circle(sr.0 + sr.2 / 2.0, sr.1 + sr.3 / 2.0, sr.2 / 2.0 - 5.0 * s, 0xFFE8E8E8);
        hits.push((sr, Act::ShotCapture));
        let rr: R = (sr.0 + sr.2 + 14.0 * s, ty0 + 10.0 * s, th_ - 20.0 * s, th_ - 20.0 * s);
        cv.fill_circle(rr.0 + rr.2 / 2.0, rr.1 + rr.3 / 2.0, rr.2 / 2.0, with_alpha(0xFFFFFFFF, 0.08));
        cv.fill_circle(rr.0 + rr.2 / 2.0, rr.1 + rr.3 / 2.0, 7.0 * s, 0xFFE5484D);
        hits.push((rr, Act::ShotRecord));
        let xr: R = (rr.0 + rr.2 + 10.0 * s, ty0 + 14.0 * s, th_ - 28.0 * s, th_ - 28.0 * s);
        pt.icon(cv, "window-close-symbolic", xr.0 + 4.0 * s, xr.1 + 4.0 * s, xr.2 - 8.0 * s, 0xFFFFFFFF);
        hits.push((xr, Act::ShotClose));
        sh.pane.hits = hits;
        let id = sh.pane.id;
        self.p.present(id, &sh.pane.cv, 0xFF000000);
        self.shot = Some(sh);
    }

    // ---------------- recording ----------------
    pub fn recording(&self) -> bool {
        self.rec.is_some()
    }

    pub fn record_toggle(&mut self) {
        if self.rec.is_some() {
            self.stop_record();
        } else {
            self.start_record(None);
        }
    }

    pub fn start_record(&mut self, region: Option<R>) {
        if self.rec.is_some() {
            return;
        }
        let wayland = std::env::var("WAYLAND_DISPLAY").is_ok() && self.p.name() == "wayland";
        let tool = if wayland { "wf-recorder" } else { "ffmpeg" };
        if !desktop::which(tool) {
            self.toast(&format!("Screen recording needs {} installed", tool));
            return;
        }
        let dir = expand_home(&self.cfg.video_dir);
        if std::fs::create_dir_all(&dir).is_err() {
            self.toast("Cannot create the Videos folder");
            return;
        }
        let path = dir.join(format!("Screencast from {}.mp4", stamp()));
        let o = self.out();
        let (rx, ry, rw, rh) = match region {
            Some(r) => (r.0 as i32 + o.x, r.1 as i32 + o.y, r.2 as i32, r.3 as i32),
            None => (o.x, o.y, o.w, o.h),
        };
        let (rw, rh) = (rw & !1, rh & !1);
        let fps = self.cfg.record_fps.to_string();
        let mut args: Vec<String> = vec![];
        if wayland {
            args.push("-f".into());
            args.push(path.to_string_lossy().to_string());
            if region.is_some() {
                args.push("-g".into());
                args.push(format!("{},{} {}x{}", rx, ry, rw, rh));
            }
            args.push("-r".into());
            args.push(fps);
            if self.cfg.record_audio {
                args.push("-a".into());
            }
        } else {
            let disp = std::env::var("DISPLAY").unwrap_or_else(|_| ":0".into());
            for a in ["-y", "-loglevel", "error", "-f", "x11grab", "-framerate", &fps, "-video_size", &format!("{}x{}", rw, rh), "-i", &format!("{}+{},{}", disp, rx, ry)] {
                args.push(a.to_string());
            }
            if self.cfg.record_audio {
                for a in ["-f", "pulse", "-i", "default"] {
                    args.push(a.to_string());
                }
            }
            for a in ["-c:v", "libx264", "-preset", "ultrafast", "-crf", "23", "-pix_fmt", "yuv420p"] {
                args.push(a.to_string());
            }
            if self.cfg.record_audio {
                args.push("-c:a".into());
                args.push("aac".into());
            }
            args.push(path.to_string_lossy().to_string());
        }
        use std::os::unix::process::CommandExt;
        match std::process::Command::new(tool).args(&args).stdin(std::process::Stdio::null()).stdout(std::process::Stdio::null()).stderr(std::process::Stdio::null()).process_group(0).spawn() {
            Ok(child) => {
                self.rec = Some(Recorder { child, path, started: Instant::now(), stopping: None });
                if let Some(b) = &mut self.bar {
                    b.dirty = true;
                }
            }
            Err(e) => self.toast(&format!("Could not start {}: {}", tool, e)),
        }
    }

    pub fn stop_record(&mut self) {
        if let Some(r) = &mut self.rec {
            if r.stopping.is_none() {
                crate::sys::sys_kill(r.child.id() as i32, 2); // SIGINT: encoders finalize the mp4 cleanly
                r.stopping = Some(Instant::now());
            }
        }
    }

    pub fn record_tick(&mut self) {
        let mut done: Option<(std::path::PathBuf, bool)> = None;
        if let Some(r) = &mut self.rec {
            match r.child.try_wait() {
                Ok(Some(st)) => done = Some((r.path.clone(), st.success() || r.stopping.is_some())),
                Ok(None) => {
                    if r.stopping.map_or(false, |t| t.elapsed() > Duration::from_secs(8)) {
                        let _ = r.child.kill();
                    }
                    if self.cfg.manage_panel || true {
                        if let Some(b) = &mut self.bar {
                            if r.started.elapsed().as_millis() % 1000 < 400 || true {
                                b.dirty = true;
                            }
                        }
                    }
                }
                Err(_) => done = Some((r.path.clone(), false)),
            }
        }
        if let Some((path, ok)) = done {
            self.rec = None;
            if ok && path.exists() {
                self.local_notify("Screencast recorded", &path.to_string_lossy(), "camera-video-symbolic", &path.to_string_lossy());
            } else {
                self.toast("Recording failed (check the encoder)");
            }
            if let Some(b) = &mut self.bar {
                b.dirty = true;
            }
        }
    }

    pub fn rec_elapsed(&self) -> Option<String> {
        self.rec.as_ref().map(|r| {
            let s = r.started.elapsed().as_secs();
            format!("{:02}:{:02}", s / 60, s % 60)
        })
    }

    // ---------------- labwc keybind installer ----------------
    fn labwc_key(accel: &str) -> Option<String> {
        let (sym, mods) = parse_accel(accel)?;
        let mut k = String::new();
        if mods & 1 != 0 {
            k += "S-";
        }
        if mods & 2 != 0 {
            k += "C-";
        }
        if mods & 4 != 0 {
            k += "A-";
        }
        if mods & 8 != 0 {
            k += "W-";
        }
        let name = match sym {
            0xff61 => "Print".to_string(),
            0xff13 => "Pause".into(),
            0xffbe..=0xffc9 => format!("F{}", sym - 0xffbd),
            0x20 => "space".into(),
            0xff0d => "Return".into(),
            0xff09 => "Tab".into(),
            0x21..=0x7e => (sym as u8 as char).to_ascii_lowercase().to_string(),
            _ => return None,
        };
        Some(k + &name)
    }

    pub fn labwc_rc() -> std::path::PathBuf {
        let base = std::env::var("XDG_CONFIG_HOME").ok().filter(|s| !s.is_empty()).map(std::path::PathBuf::from).or_else(|| std::env::var("HOME").ok().map(|h| std::path::PathBuf::from(h).join(".config"))).unwrap_or_else(|| "/tmp".into());
        base.join("labwc/rc.xml")
    }

    pub fn labwc_installed() -> bool {
        std::fs::read_to_string(Self::labwc_rc()).map_or(false, |t| t.contains("lumen-shortcuts-begin"))
    }

    fn strip_block(t: &str) -> String {
        match (t.find("<!-- lumen-shortcuts-begin -->"), t.find("<!-- lumen-shortcuts-end -->")) {
            (Some(a), Some(b)) if b > a => {
                let end = b + "<!-- lumen-shortcuts-end -->".len();
                format!("{}{}", &t[..a].trim_end_matches([' ', '\t']), t[end..].trim_start_matches('\n'))
            }
            _ => t.to_string(),
        }
    }

    pub fn labwc_install(&mut self, install: bool) {
        let rc = Self::labwc_rc();
        let exe = std::env::current_exe().map(|e| e.to_string_lossy().to_string()).unwrap_or_else(|_| "lumen".into());
        let _ = std::fs::create_dir_all(rc.parent().unwrap_or(std::path::Path::new("/tmp")));
        let existing = std::fs::read_to_string(&rc).unwrap_or_else(|_| "<?xml version=\"1.0\"?>\n<labwc_config>\n</labwc_config>\n".into());
        if rc.exists() && !rc.with_extension("xml.lumen.bak").exists() {
            let _ = std::fs::copy(&rc, rc.with_extension("xml.lumen.bak"));
        }
        let mut text = Self::strip_block(&existing);
        if install {
            let cmds = ["--screenshot", "--shot-screen", "--shot-area", "--record", "--toggle-grid"];
            let mut block = String::from("<!-- lumen-shortcuts-begin -->\n");
            for (i, c) in cmds.iter().enumerate() {
                if let Some(k) = Self::labwc_key(&self.cfg.sc[i]) {
                    block += &format!("    <keybind key=\"{}\"><action name=\"Execute\" command=\"{} {}\" /></keybind>\n", k, exe, c);
                }
            }
            block += "    <!-- lumen-shortcuts-end -->\n";
            if let Some(i) = text.find("</keyboard>") {
                text.insert_str(i, &block);
            } else if let Some(i) = text.find("</labwc_config>") {
                text.insert_str(i, &format!("<keyboard>\n    {}</keyboard>\n", block));
            }
        }
        if std::fs::write(&rc, text).is_ok() {
            self.spawn_cmd(&["labwc", "--reconfigure"]);
            self.toast(if install { "Shortcuts installed in labwc" } else { "Shortcuts removed from labwc" });
        } else {
            self.toast("Could not write the labwc config");
        }
    }

    pub fn accel_label(&self, i: usize) -> String {
        self.cfg.sc[i].clone()
    }

    pub fn capture_accel(&mut self, slot: usize, sym: u32, mods: u8) {
        if let Some(a) = accel_name(sym, mods) {
            self.cfg.sc[slot] = a;
            self.save_cfg_quiet();
            self.register_shortcuts();
        }
    }
}
